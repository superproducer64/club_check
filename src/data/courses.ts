export function generateCustomCourse(name: string, location: string, lat?: number, lng?: number): GolfCourse {
  const baseLat = lat ?? 36.568;
  const baseLng = lng ?? -121.947;
  const [city, state] = location.split(',').map((part) => part.trim());

  return {
    id: `custom-${Date.now()}`,
    name: name || 'Custom Local Course',
    location: location || 'Local Golf Club',
    city: city || 'Local',
    state: state || 'US',
    holesCount: 18,
    parTotal: 72,
    totalYards: 6500,
    holes: Array.from({ length: 18 }, (_, i) => ({
      holeNumber: i + 1,
      par: [4, 5, 4, 3, 4, 4, 5, 3, 4, 4, 3, 5, 4, 4, 3, 5, 4, 4][i],
      handicap: i + 1,
      yardage: 320 + (i % 5) * 45,
      greenLat: baseLat + i * 0.0015,
      greenLng: baseLng + i * 0.0012,
      teeLat: baseLat + i * 0.0015 - 0.0011,
      teeLng: baseLng + i * 0.0012 - 0.0008,
    })),
  };
}
